int main(int argc, char** argv) {
    if (argc >= 4 && std::string(argv[1]) == "--ensure") return ensure(argv[2], argv[3]);
    if (argc >= 2 && std::string(argv[1]) == "--geometry") return geometry();
    if (argc >= 3 && std::string(argv[1]) == "--view") return viewPass(argv[2]);
    if (argc >= 3 && std::string(argv[1]) == "--plates")
        return plates(argv[2], argc >= 4 ? argv[3] : "", argc >= 5 ? argv[4] : "");
    if (argc >= 3 && std::string(argv[1]) == "--overlay")
        return overlayGate(argv[2], argc >= 4 ? argv[3] : "");
    if (argc >= 3 && std::string(argv[1]) == "--readers") return readers(argv[2]);
    if (argc >= 3 && std::string(argv[1]) == "--pages") return pages(argv[2], argc >= 4 ? argv[3] : "");
    if (argc >= 3 && std::string(argv[1]) == "--catalogue")
        return catalogue(argv[2], argc >= 4 ? argv[3] : "");
    std::fprintf(stderr, "usage: test_catalogue --readers <dump.txt> | --catalogue <oracle.bin> [<out.bin>] | "
                         "--pages <data dir> [<out dir>] | --ensure <data dir> <mod dir> | "
                         "--overlay <data dir> [<out dir>] | --geometry | --plates <data dir> | --view <dir>\n");
    return 2;
}
