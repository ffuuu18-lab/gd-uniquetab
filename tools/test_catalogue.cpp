// Peak working set of this process, in MB. PeakWorkingSetSize only ever grows, so a sample
// taken right after the first generation is that generation's peak - which is why --ensure
// measures its FIRST pass, before anything else here has allocated.
double peakWorkingSetMb() {
    PROCESS_MEMORY_COUNTERS pmc;
    if (!GetProcessMemoryInfo(GetCurrentProcess(), &pmc, sizeof pmc)) return 0.0;
    return double(pmc.PeakWorkingSetSize) / (1024.0 * 1024.0);
}

// The record as Python's arz.py sees it: the last field of a name wins, sorted by name.
void dumpRecord(FILE* out, const gen::ArzRecord& rec) {
    std::map<std::string, const gen::ArzField*> last;
    for (const gen::ArzField& f : rec.fields) last[f.name] = &f;
    for (const auto& kv : last) {
        const gen::ArzField& f = *kv.second;
        std::fprintf(out, "  %s\t%u\t", kv.first.c_str(), unsigned(f.type));
        for (std::size_t i = 0; i < f.raw.size(); ++i) {
            if (i) std::fputc(',', out);
            if (f.type == gen::kFtString) std::fputs(f.strs[i].c_str(), out);
            else if (f.type == gen::kFtFloat) std::fprintf(out, "%08x", f.raw[i]);
            else std::fprintf(out, "%d", int(f.raw[i]));
        }
        std::fputc('\n', out);
    }
}

int readers(const std::string& dumpPath) {
    std::string game = gameDir();
    if (game.empty()) return fail("UNIQUETAB_TEST_GAME_DIR is not set");
    auto t0 = std::chrono::steady_clock::now();
    gen::ArzDatabase db;
    std::string err;
    if (!db.loadGame(game, &err)) return fail(err.c_str());
    std::unordered_map<std::string, std::string> tags;
    if (!gen::loadTextTags(game, "EN", tags, &err)) return fail(err.c_str());
    gen::ArcSet items, ui;
    if (!items.load(game, "resources\\Items.arc", &err)) return fail(err.c_str());
    if (!ui.load(game, "resources\\UI.arc", &err)) return fail(err.c_str());
    auto ms = std::chrono::duration_cast<std::chrono::milliseconds>(
        std::chrono::steady_clock::now() - t0).count();

    FILE* out = std::fopen(dumpPath.c_str(), "wb");
    if (!out) return fail("cannot write the dump");
    for (const gen::ArzArchive& a : db.archives())
        std::fprintf(out, "arz\t%s\t%zu\t%zu\n", a.tag().c_str(), a.recordCount(), a.stringCount());
    std::fprintf(out, "merged\t%zu\n", db.size());
    std::fprintf(out, "tags\t%zu\n", tags.size());
    std::fprintf(out, "items.arc\t%zu\n", items.size());
    std::fprintf(out, "ui.arc\t%zu\n", ui.size());

    const auto& w = db.winners();
    std::size_t step = w.size() / 200;
    if (step == 0) step = 1;
    std::size_t decoded = 0;
    for (std::size_t i = 0; i < w.size() && decoded < 200; i += step, ++decoded) {
        const gen::ArzArchive& a = db.archives()[w[i].first];
        gen::ArzRecord rec;
        if (!a.decode(*w[i].second, rec)) { std::fclose(out); return fail("record decode"); }
        std::fprintf(out, "record\t%s\t%s\n", w[i].second->key.c_str(), a.tag().c_str());
        dumpRecord(out, rec);
    }
    std::vector<std::string> keys;
    keys.reserve(tags.size());
    for (const auto& kv : tags) keys.push_back(kv.first);
    std::sort(keys.begin(), keys.end());
    std::size_t tstep = keys.size() / 200;
    if (tstep == 0) tstep = 1;
    for (std::size_t i = 0; i < keys.size(); i += tstep)
        std::fprintf(out, "tag\t%s=%s\n", keys[i].c_str(), tags[keys[i]].c_str());
    std::fclose(out);

    // Every record of every archive decodes: the LZ4 decoder against the whole database.
    std::size_t total = 0;
    gen::ArzRecord rec;
    for (const gen::ArzArchive& a : db.archives())
        for (const gen::ArzEntry& e : a.entries()) {
            if (!a.decode(e, rec)) {
                std::fprintf(stderr, "[test] decode failed: %s %s\n", a.tag().c_str(), e.name.c_str());
                return 1;
            }
            ++total;
        }
    auto ms2 = std::chrono::duration_cast<std::chrono::milliseconds>(
        std::chrono::steady_clock::now() - t0).count();
    std::printf("[test] readers: %zu merged records, %zu tags, %zu Items.arc, %zu UI.arc entries;"
                " load %lld ms, all %zu records decoded in %lld ms\n",
                db.size(), tags.size(), items.size(), ui.size(), (long long)ms, total, (long long)ms2);
    return 0;
}

bool readAll(const std::string& path, std::vector<std::uint8_t>& out) {
    FILE* f = std::fopen(path.c_str(), "rb");
    if (!f) return false;
    std::fseek(f, 0, SEEK_END);
    long n = std::ftell(f);
    std::fseek(f, 0, SEEK_SET);
    out.resize(n > 0 ? std::size_t(n) : 0);
    bool ok = out.empty() || std::fread(out.data(), 1, out.size(), f) == out.size();
    std::fclose(f);
    return ok;
}

// Prints the first differing offset with 16 bytes of context on both sides.
int compareBytes(const char* what, const std::vector<std::uint8_t>& got,
                 const std::vector<std::uint8_t>& want) {
    std::size_t n = std::min(got.size(), want.size()), at = n;
    for (std::size_t i = 0; i < n; ++i) if (got[i] != want[i]) { at = i; break; }
    if (at == n && got.size() == want.size()) {
        std::printf("[test] %s: byte-identical (%zu B)\n", what, got.size());
        return 0;
    }
    std::printf("[test] FAIL: %s differs at offset %zu (generated %zu B, oracle %zu B)\n",
                what, at, got.size(), want.size());
    std::size_t from = at >= 16 ? at - 16 : 0;
    for (int side = 0; side < 2; ++side) {
        const auto& v = side ? want : got;
        std::printf("  %s:", side ? "oracle   " : "generated");
        for (std::size_t i = from; i < from + 48 && i < v.size(); ++i) std::printf(" %02x", v[i]);
        std::printf("\n            ");
        for (std::size_t i = from; i < from + 48 && i < v.size(); ++i)
            std::printf(" %c ", v[i] >= 32 && v[i] < 127 ? char(v[i]) : '.');
        std::printf("\n");
    }
    return 1;
}

