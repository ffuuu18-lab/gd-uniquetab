// test_catalogue.cpp - offline harness for src\gen: the archive readers and the generator.
// Reads the game folder named by UNIQUETAB_TEST_GAME_DIR, writes only under build\test.
//
//   test_catalogue.exe --readers <dump.txt>      counts + a deterministic sample of decoded
//                                                records and text tags (diffed against
//                                                tools\dump_gen_sample.py's output)
//   test_catalogue.exe --catalogue <oracle.bin> [<out.bin>]
//                                                generates catalogue.bin from the game folder
//                                                and compares it byte for byte with the oracle
//                                                file; the generated bytes go to <out.bin>
//   test_catalogue.exe --pages <data dir> [<out dir>]
//                                                the three uniq txt files against data\oracle,
//                                                plus the read-back of the generated overlay
//   test_catalogue.exe --overlay <data dir> [<out dir>]
//                                                the generated uniq-pages.arz against the
//                                                oracle data\oracle\uniq-pages.arz, record for
//                                                record: name, type, timestamp, every field
//   test_catalogue.exe --geometry                the grid rectangle and the plate derived from
//                                                the vanilla database, and - when
//                                                UNIQUETAB_TEST_MODS_DIR names the unpacked
//                                                stash mods - from those two as well
//   test_catalogue.exe --plates <data dir> [dump dir] [RRGGBB]
//                                                the painted cover plates: byte-identical to
//                                                data\oracle\plates on the vanilla view, a flat ground
//                                                on the two modded ones. The third argument is
//                                                uniquetab.ini's plate_ground.
//   test_catalogue.exe --ensure <data dir> <mod dir>
//                                                the DLL's start-up path (gen::ensureOutputs)
